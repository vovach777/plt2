# as2cpp.py - test bench for the AssemblyScript ports (palic-2r-as/*.ts) without the AS compiler: a mechanical
# translation of the (restricted) AS subset they use into C++ with wasm32 semantics: one linear memory (usize = u32,
# load<T>/store<T> little-endian at MEM + p), memory.data<u8>([...]) placed at fixed offsets, <T>x casts as C casts
# (same precedence as AS prefix casts), clz/ctz/popcnt, i32 wrap-around (-fwrapv). Shift counts >= width are UB in C++
# (masked in wasm): build the bench with -fsanitize=shift to catch them. Not a general AS compiler; it handles the
# constructs these ports use and fails loudly on anything else it does not know.
# usage: as2cpp.py in.ts > out.cpp   (then: g++ -std=c++17 -O2 -fwrapv out.cpp harness.cpp)
import re, sys
T = {'i8': 'int8_t', 'u8': 'uint8_t', 'i16': 'int16_t', 'u16': 'uint16_t', 'i32': 'int32_t', 'u32': 'uint32_t',
     'i64': 'int64_t', 'u64': 'uint64_t', 'usize': 'uint32_t', 'isize': 'int32_t', 'bool': 'bool', 'void': 'void',
     'f64': 'double', 'f32': 'float'}
TY = '|'.join(T)
src = open(sys.argv[1]).read()
src = re.sub(r'/\*.*?\*/', '', src, flags=re.S)
out = ['// generated by as2cpp.py from ' + sys.argv[1] + ' - do not edit', '#include "as_rt.hpp"']
data = []                                           # (name, type, values)
def repl_data(m):
    name, ty, body = m.group(1), m.group(2), m.group(3)
    vals = [v.strip() for v in body.replace('\n', ' ').split(',') if v.strip()]
    data.append((name, ty, vals)); return f'static uint32_t {name} = 0;  // static data <{ty}> x {len(vals)}'
src = re.sub(r'const\s+(\w+)\s*=\s*memory\.data<(\w+)>\(\[(.*?)\]\);', repl_data, src, flags=re.S)
def typ(t): 
    t = t.strip()
    if t not in T: raise SystemExit('as2cpp: unknown type ' + t)
    return T[t]
def params(p):
    p = p.strip()
    if not p: return ''
    out = []
    for a in p.split(','):
        n, t = a.split(':'); out.append(f'{typ(t)} {n.strip()}')
    return ', '.join(out)
lines = src.split('\n'); res = []; protos = []
for ln in lines:
    s = ln
    m = re.match(r'^(\s*)(export\s+)?function\s+(\w+)\s*\(([^)]*)\)\s*:\s*(\w+)\s*\{(.*)$', s)
    if m:
        ind, exp, name, ps, rt, rest = m.groups()
        s = f'{ind}{"" if exp else "static "}{typ(rt)} {name}({params(ps)}) {{{rest}'
        protos.append(f'{"" if exp else "static "}{typ(rt)} {name}({params(ps)});')
    s = re.sub(r'\bfor\s*\(\s*let\s+(\w+)\s*:\s*(\w+)\s*=', lambda m: f'for ({typ(m.group(2))} {m.group(1)} =', s)
    s = re.sub(r'\bfor\s*\(\s*let\s+(\w+)\s*=', r'for (int32_t \1 =', s)
    s = re.sub(r'^(\s*)let\s+(\w+)\s*:\s*(\w+)\s*=', lambda m: f'{m.group(1)}{"static " if not m.group(1) else ""}{typ(m.group(3))} {m.group(2)} =', s)
    s = re.sub(r'^(\s*)const\s+(\w+)\s*:\s*(\w+)\s*=', lambda m: f'{m.group(1)}{"static " if not m.group(1) else ""}const {typ(m.group(3))} {m.group(2)} =', s)
    s = re.sub(r'^(\s*)let\s+(\w+)\s*:\s*(\w+)\s*;', lambda m: f'{m.group(1)}{"static " if not m.group(1) else ""}{typ(m.group(3))} {m.group(2)}{{}};', s)
    s = re.sub(r'^(\s*)let\s+(\w+)\s*=', lambda m: f'{m.group(1)}{"static " if not m.group(1) else ""}auto {m.group(2)} =', s)
    s = re.sub(r'^(\s*)const\s+(\w+)\s*=', lambda m: f'{m.group(1)}{"static " if not m.group(1) else ""}const auto {m.group(2)} =', s)
    s = re.sub(r'\bload<(' + TY + r')>\(', lambda m: f'ld<{typ(m.group(1))}>(', s)
    s = re.sub(r'\bstore<(' + TY + r')>\(', lambda m: f'st<{typ(m.group(1))}>(', s)
    s = re.sub(r'\b(clz|ctz|popcnt)<(u32|i32)>\(', r'\1_32(', s)
    s = re.sub(r'\b(clz|ctz|popcnt)<(u64|i64)>\(', r'\1_64(', s)
    s = re.sub(r'(?<![\w>])<(' + TY + r')>', lambda m: f'({typ(m.group(1))})', s)
    s = s.replace('memory.size()', 'mem_size()').replace('memory.grow(', 'mem_grow(').replace('memory.copy(', 'mem_copy(').replace('memory.fill(', 'mem_fill(')
    if re.search(r'\b(let|function|memory\.|unchecked|changetype|instantiate)\b', s): raise SystemExit('as2cpp: unhandled: ' + ln)
    res.append(s)
out += protos + res
out.append('static void as_static_init() {'); off = 1024
for name, ty, vals in data:
    ct = typ(ty); sz = {'uint8_t': 1, 'int8_t': 1, 'uint16_t': 2, 'int16_t': 2, 'uint32_t': 4, 'int32_t': 4}[ct]
    out.append(f'  {name} = {off}; {{ static const {ct} v[] = {{{",".join(vals)}}}; memcpy(MEM + {off}, v, sizeof v); }}')
    off = (off + sz * len(vals) + 15) & ~15
out.append(f'}}\nstatic const uint32_t AS_DATA_END = {off};')
print('\n'.join(out))
