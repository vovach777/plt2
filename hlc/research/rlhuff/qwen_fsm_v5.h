// contexts of one stream of tokens (cr = run class, cv = half-octave value class), causal
template <class Tok> static void qwen_fsm_ctx(const std::vector<Tok>& t, std::vector<int>& out) {
    out.resize(t.size()); int a2 = 0, a8 = 0, r8 = 0, dmax = 0, amp8 = 0, pr = 255, pcv = 255;
    for (size_t i = 0; i < t.size(); ++i) {
        const int cr = t[i].cr, cv = t[i].cv, vb = cv == 0 ? 0 : cv == 1 ? 1 : (cv + 2) / 2, V = vb * 8, R = cr * 8;
        const int F[7] = {a2, a8, amp8, dmax, pcv, pr, r8};
        int v = 0; while (QWEN_FSM[v].f >= 0) v = F[QWEN_FSM[v].f] <= QWEN_FSM[v].thr ? QWEN_FSM[v].l : QWEN_FSM[v].r;
        out[i] = QWEN_FSM[v].l;
        a2 += (V - a2 + 1) >> 1; a8 += (V - a8 + 4) >> 3; r8 += (R - r8 + 4) >> 3;
        dmax = V > dmax - 6 ? V : dmax - 6;
        const int a = 1 << (vb < 8 ? vb : 8); amp8 += ((a < 255 ? a : 255) - amp8 + 8) >> 4;
        pr = cr; pcv = cv;
    }
}
