# gen_qhs_tables.py - writes palic-2/qhs_tables.h (the screen mode tables) from an exp_hybrid.py table pickle, variant H0.
# usage: gen_qhs_tables.py TABLES.pkl OUT.h "training note"
import sys, pickle, numpy as np
mp, lens, ks = pickle.load(open(sys.argv[1], 'rb'))['H0']; out = sys.argv[2]; note = sys.argv[3]
assert len(mp) == 136 and lens.shape == (32, 256) and lens.max() <= 11 and ks.max() <= 6
assert np.allclose((2.0 ** -lens.astype(float)).sum(1), 1)
L = ['// qhs_tables.h - the static tables of the PLR screen mode (PLS): Sparse-Raw split, Ls = clamp(bw(max(sa, sl) >> 4) - 2, 0, 7),',
     '// letters of min(h, 3) by 4, tails h - 3: Rice(k) with escape 8 ones + Exp-Golomb order 2.',
     '// generated by ../hlc/research/qh_enc/gen_qhs_tables.py from exp_hybrid.py (variant H0); ' + note,
     '// Do not edit: a change of any number changes the format.', '#pragma once', '#include <cstdint>', 'namespace qhs_tab {',
     'constexpr int K = 32, ML = 11, NQ = 68;', 'constexpr uint8_t ctxmap[2 * NQ] = {']
L += ['    ' + ', '.join(str(int(x)) for x in mp[i:i + 32]) + ',' for i in range(0, 136, 32)]
L[-1] = L[-1][:-1] + ' };'; L.append('constexpr uint8_t lens[K][256] = {')
for t in range(32): L.append('  {' + ', '.join(str(int(x)) for x in lens[t]) + '}' + (',' if t < 31 else ''))
L += ['};', 'constexpr uint8_t rk[K] = { ' + ', '.join(str(int(x)) for x in ks) + ' };', '}  // namespace qhs_tab', '']
open(out, 'w').write('\n'.join(L))
