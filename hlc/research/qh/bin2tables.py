# bin2tables.py - QH tables (.bin from train_stream.py / train_tables.py) -> C++ header (qh_tables.h layout) or
# AssemblyScript arrays (CTX / RK / LENS as in palic-2r-as/plr.ts).
# .bin: int32 K, ML, NQ, QESC; uint8 ctxmap[2 * NQ]; uint8 lens[K][256]; uint8 rk[K]
# usage: bin2tables.py tables.bin h|ts [note] > out
import sys, struct, numpy as np
b = open(sys.argv[1], 'rb').read(); K, ML, NQ, QESC = struct.unpack('<4i', b[:16]); o = 16
ctx = np.frombuffer(b, np.uint8, 2 * NQ, o); o += 2 * NQ
lens = np.frombuffer(b, np.uint8, K * 256, o).reshape(K, 256); o += K * 256
rk = np.frombuffer(b, np.uint8, K, o); o += K
assert o == len(b) and lens.max() <= ML and np.allclose((2.0 ** -lens.astype(float)).sum(1), 1), 'bad table file'
row = lambda a: ', '.join(str(int(x)) for x in a)
note = sys.argv[3] if len(sys.argv) > 3 else ''
if sys.argv[2] == 'h':
    print('// qh_tables.h - static QH tables (generated by hlc/research/qh/bin2tables.py from %s). %s' % (sys.argv[1].split('/')[-1], note))
    print('// Do not edit: a change of any number changes the format.\n#pragma once\n#include <cstdint>\nnamespace qh_tab {')
    print(f'constexpr int K = {K}, ML = {ML}, NQ = {NQ}, QESC = {QESC};')
    print('constexpr uint8_t ctxmap[2 * NQ] = {'); print(',\n'.join('    ' + row(ctx[i:i + 32]) for i in range(0, 2 * NQ, 32)) + ' };')
    print('constexpr uint8_t lens[K][256] = {'); print(',\n'.join('  {' + row(lens[t]) + '}' for t in range(K))); print('};')
    print('constexpr uint8_t rk[K] = { ' + row(rk) + ' };\n}  // namespace qh_tab')
else:
    print(f'// generated by hlc/research/qh/bin2tables.py from {sys.argv[1].split("/")[-1]}: K={K} ML={ML} NQ={NQ} QESC={QESC}. {note}')
    print('const CTX = memory.data<u8>([\n  ' + row(ctx) + '\n]);')
    print('const RK = memory.data<u8>([\n  ' + row(rk) + '\n]);')
    print('const LENS = memory.data<u8>([\n' + ',\n'.join('  ' + row(lens[t]) for t in range(K)) + '\n]);')
