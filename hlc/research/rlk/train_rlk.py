#!/usr/bin/env python3
"""Train the RLK Huffman tables (ctx6, long runs) from RLK_DUMP files and export them for plrk.ts.

usage: RLK_LONG=1 python3 train_rlk.py out.ts dump1.bin,dump2.bin
Writes an AssemblyScript file with RLK_LEN = memory.data<u8>(2 * 225 * 176): code lengths (1..14) per
(plane, context, symbol); plane 0 = Y, 1 = S.
"""
import os, sys
os.environ.setdefault('RLK_LONG', '1')
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import numpy as np
import rlk_model as m

out, train = sys.argv[1], sys.argv[2].split(',')
NCTX = 225
cnt = np.zeros((2, NCTX, m.NSYM))
for p in train:
    for tw, th, yb, sb, zy, s, zu in m.tiles(p):
        for pl, z in ((0, zy), (1, s)):
            S, C, _ = m.symbols(z, tw, 6)
            np.add.at(cnt[pl], (C, S), 1)
L = np.zeros((2, NCTX, m.NSYM), np.int64)
for pl in range(2):
    for c in range(NCTX):
        L[pl, c] = m.huff_lengths(cnt[pl, c] + 0.5)
assert L.min() >= 1 and L.max() <= m.MAXLEN and m.NSYM == 176
# Kraft check: canonical codes must exist
for pl in range(2):
    for c in range(NCTX):
        assert abs(sum(2.0 ** -L[pl, c]) - 1.0) < 1e-9 or sum(2.0 ** -L[pl, c]) <= 1.0
flat = L.ravel()
with open(out, 'w') as f:
    f.write('// RLK Huffman code lengths, generated by hlc/research/rlk/train_rlk.py from: ' + ' '.join(os.path.basename(p) for p in train) + '\n')
    f.write('// [plane (0 = Y, 1 = S)][context 0..224][symbol 0..175], lengths 1..14\n')
    f.write('const RLK_LEN = memory.data<u8>([\n')
    for i in range(0, len(flat), 40):
        f.write('  ' + ', '.join(str(int(v)) for v in flat[i:i + 40]) + ',\n')
    f.write(']);\n')
print('tables:', L.shape, 'max len', L.max(), 'bytes', flat.size)
