def harr(name,shape):
    m=re.search(name+r'\['+r'\]\['.join(map(str,shape))+r'\] = \{(.*?)\};',h,re.S)
    return np.array([int(x) for x in m.group(1).replace('\n','').split(',') if x.strip()]).reshape(shape)
A={}
# A31 from PLT1 tables: letters 0..30
A['31']=dict(LO=harr('LO',(2,32))[:,:31], RAW=harr('RAW',(2,32))[:,:31], SIGN=harr('SIGN',(2,32))[:,:31])
# A15: 0, +classes 1..7, -classes 8..14
W15={0:[1,2,4,8,16,32,128], 1:[1,1,2,4,16,128,128]}
LO=np.zeros((2,15),int); RAW=np.zeros((2,15),int); SG=np.zeros((2,15),int)
for g in (0,1):
    lo=1
    for k,w in enumerate(W15[g]):
        r=int(np.log2(w))
        for s,base in ((1,1),(-1,8)): LO[g,base+k]=lo; RAW[g,base+k]=r; SG[g,base+k]=s
        lo+=w
A['15']=dict(LO=LO,RAW=RAW,SIGN=SG)
def enc_table(a,g):
    span=128 if g==0 else 256; E=np.zeros(513,int)
    for e in range(-256,257):
        if e==0: continue
        if not (-span<=e<=span): continue
        s=1 if e>0 else -1; m=abs(e); hit=None
        for l in range(len(a['LO'][g])):
            if a['SIGN'][g][l]==s and a['LO'][g][l]<=m<a['LO'][g][l]+(1<<a['RAW'][g][l]): hit=(l,m-a['LO'][g][l]); break
        if hit: E[e+256]=hit[0]|(hit[1]<<5)
    return E
def letter_counts(J,a,g):            # J (rows, 119) -> (rows, NL), uniform inside corpus buckets
    NL=len(a['LO'][g]); M=np.zeros((NSYM,NL)); E=enc_table(a,g); span=128 if g==0 else 256
    M[0,0]=1
    for s in range(1,NSYM):
        sg=1 if SYM_SIGN[s]>0 else -1; vals=[v for v in range(SYM_LO[s],SYM_HI[s]+1) if v<=span]
        for v in vals: M[s,E[sg*v+256]&31]+=1/len(vals)
    return J@M
def quant(c,NL,lanes):
    p=c/np.maximum(c.sum(-1,keepdims=True),1)
    f=np.maximum(2,np.floor(p*(32768-2*NL)+0.5)).astype(np.int64)
    while True:
        d=32768-f.sum(-1)
        if (d==0).all(): break
        i=f.argmax(-1); np.put_along_axis(f,i[...,None],np.take_along_axis(f,i[...,None],-1)+d[...,None],-1)
    assert (f>=2).all()
    cum=np.full(f.shape[:-1]+(lanes,),32768,np.int64); cum[...,0]=0; cum[...,1:NL+1]=np.cumsum(f,-1)[..., :NL] if NL+1<=lanes else None
    cum[...,1:NL+1]=np.cumsum(f,-1); return cum
out=['// generated by gen2.py: PLT2 tables (CLIC-2020 train). Cluster LUT per component (bit7 = fold),','#pragma once','#include <cstdint>','namespace plt2_tab {']
def emit(t,name,arr,per=32):
    flat=np.asarray(arr).ravel(); dims=''.join(f'[{d}]' for d in np.asarray(arr).shape)
    out.append(f'alignas(64) static const {t} {name}{dims} = {{')
    for i in range(0,len(flat),per): out.append(','.join(str(int(x)) for x in flat[i:i+per])+',')
    out.append('};')
