    pad=lambda x,v: np.concatenate([x,np.full((2,lanes-x.shape[1]),v)],1)
    emit('uint16_t',f'LO{an}',pad(a['LO'],0)); emit('uint8_t',f'RAW{an}',pad(a['RAW'],0)); emit('int8_t',f'SIGN{an}',pad(a['SIGN'],0))
    emit('uint16_t',f'ENC{an}',np.stack([enc_table(a,0),enc_table(a,1)]),64)
    CE=[];C1=[]
