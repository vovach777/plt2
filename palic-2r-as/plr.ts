function buildCodes(): void {
  for (let k = 0; k < KTAB; k++) {
    for (let i = 0; i < 256; i++) store<i32>(WORDS + <usize>(i << 2), i);
    for (let i = 1; i < 256; i++) {
      const key = load<i32>(WORDS + <usize>(i << 2));
      const kl = lensAt(k, key);
      let j = i - 1;
      while (j >= 0 && lensAt(k, load<i32>(WORDS + <usize>(j << 2))) > kl) {
        store<i32>(WORDS + <usize>((j + 1) << 2), load<i32>(WORDS + <usize>(j << 2)));
        j--;
      }
      store<i32>(WORDS + <usize>((j + 1) << 2), key);
    }
    let code: u32 = 0;
    let prev = lensAt(k, load<i32>(WORDS));
    for (let i = 0; i < 256; i++) {
      const s = load<i32>(WORDS + <usize>(i << 2));
      const l = lensAt(k, s);
      code <<= <u32>(l - prev);
      prev = l;
      store<u16>(ENC + <usize>((k * 256 + s) << 1), <u16>code);
      const lo = code << <u32>(ML - l);
      const cnt = 1 << (ML - l);
      const base = (k << ML) + <i32>lo;
      for (let x = 0; x < cnt; x++) store<u16>(DECT + <usize>((base + x) << 1), <u16>(s | (l << 8)));
      code++;
    }
  }
  for (let i = 0; i < 256; i++) store<u64>(WORDS + <usize>(i << 3), 0);
}

