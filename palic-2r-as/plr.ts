function ricePut(x: i32, k: i32): void {
  const q = <i32>(<u32>x >> <u32>k);
  if (q >= QESC) {
    const ones = (<u64>1 << QESC) - 1;
    putBits(QESC + 10, (ones << 10) | <u64>x);
  } else {
    const mask = k ? (<u64>1 << k) - 1 : 0;
    putBits(q + 1 + k, (((<u64>2 << q) - 2) << k) | (<u64>x & mask));
  }
}
function riceGet(k: i32): i32 {
  let q = 0;
  while (getBits(1) == 1) {
    q++;
    if (q >= QESC) return getBits(10);
  }
  const low = k ? getBits(k) : 0;
  return (q << k) | low;
}

function qhEnc(base: usize, bi: i32, L: i32, pt: i32, sa: i32): void {
  const t = tableOf(pt, sa);
  const k = <i32>load<u8>(RK + <usize>t);
  const p0 = base + (<usize>(bi * 16) << 1);
  for (let q = 0; q < 4; q++) {
    let letter = 0;
    for (let j = 0; j < 4; j++) {
      let h = <i32>load<u16>(p0 + (<usize>(4 * q + j) << 1)) >> L;
      if (h > 3) h = 3;
      letter |= h << (2 * j);
    }
    putBits(lensAt(t, letter), <u64>encAt(t, letter));
  }
  for (let j = 0; j < 16; j++) {
    const h = <i32>load<u16>(p0 + (<usize>j << 1)) >> L;
    if (h >= 3) ricePut(h - 3, k);
  }
  for (let b = 0; b < L; b++) {
    let m = 0;
    for (let j = 0; j < 16; j++) m |= ((<i32>load<u16>(p0 + (<usize>j << 1)) >> b) & 1) << j;
    putBits(16, <u64>m);
  }
}
function qhDec(base: usize, bi: i32, L: i32, pt: i32, sa: i32): void {
  const t = tableOf(pt, sa);
  const k = <i32>load<u8>(RK + <usize>t);
  const h0 = HS;
  const m0 = MS;
  for (let q = 0; q < 4; q++) {
    const e = <i32>load<u16>(DECT + <usize>(((t << ML) + <i32>(peek() >> <u64>(64 - ML))) << 1));
    skipBitsLocal(e >> 8);
    const letter = e & 255;
    for (let j = 0; j < 4; j++) store<u16>(h0 + <usize>((4 * q + j) << 1), <u16>((letter >> (2 * j)) & 3));
  }
  for (let j = 0; j < 16; j++) {
    if (<i32>load<u16>(h0 + (<usize>j << 1)) == 3) store<u16>(h0 + (<usize>j << 1), <u16>(3 + riceGet(k)));
  }
  for (let b = 0; b < L; b++) store<u16>(m0 + (<usize>b << 1), <u16>getBits(16));
  const p0 = base + (<usize>(bi * 16) << 1);
  for (let j = 0; j < 16; j++) {
    let v = <i32>load<u16>(h0 + (<usize>j << 1)) << L;
    for (let b = 0; b < L; b++) if ((<i32>load<u16>(m0 + (<usize>b << 1)) >> j) & 1) v |= 1 << b;
    store<u16>(p0 + (<usize>j << 1), <u16>v);
  }
}
