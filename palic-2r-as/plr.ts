function peekAt(pos: u64): u64 {
  const i = <i32>(pos >> 6);
  const off = <i32>(pos & 63);
  const w0 = wordAt(i);
  if (off == 0) return w0;
  return (w0 << off) | (wordAt(i + 1) >> (64 - off));
}
